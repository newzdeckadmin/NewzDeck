#!/usr/bin/env node
'use strict';
// Exact v3.7.20 media-set classifier behavior; no live application or disk changes.
const fs=require('fs'), vm=require('vm');
const assert=require('assert').strict;
const source=fs.readFileSync('src/app/static/app.js','utf8');
const start=source.indexOf('function mediaSetNormalizeBase(');
const end=source.indexOf('function resetMediaSetIndex()',start);
assert(start>=0&&end>start,'Could not isolate the Image Sets classifier');
const ctx={articleGroup:a=>a.group||'alt.test'};
vm.createContext(ctx);vm.runInContext(source.slice(start,end),ctx);
const a=(filename,from='Alice <poster@example.com>',group='alt.test',kind='image',subject='')=>({subject,from,group,media:{kind,filename}});
const key=(filename,...other)=>ctx.mediaSetKey(a(filename,...other));
const seq=(filename,...other)=>ctx.mediaSetSequenceBase(a(filename,...other));
const sameGroup=(files,label)=>{
 const keys=files.map(f=>key(f));
 assert(keys[0],`No set key for ${label}: ${files[0]}`);
 assert.equal(new Set(keys).size,1,`Members split across groups for ${label}: ${JSON.stringify(keys)}`);
 assert.equal(new Set(files.map(f=>seq(f).index)).size,files.length,`Bad sequence index for ${label}`);
 return keys[0];
};
const dated=['0001_2026-06-05.png','0002_2026-06-05.png','0003_2026-06-05.png','0004_2026-06-05.png'];
const main=sameGroup(dated,'exact user filenames');
assert.equal(seq(dated[0]).base,'2026-06-05','Date should be the album base, not the first image counter');
assert.equal(seq(dated[0]).index,1);
assert.equal(seq(dated[3]).index,4);
assert.equal(seq(dated[0]).normalized,'2026 06 05');
assert.equal(main,key('001-2026-06-05.jpg'),'Hyphenated leading counter');
assert.equal(main,key('0005_2026.06.05.webp'),'Dotted date');
assert.equal(main,key('0006_2026_06_05.jpeg'),'Underscored date');
assert.equal(main,key('[07] 2026-06-05.png'),'Bracketed counter');
assert.equal(main,key('#08_2026-06-05.jpg'),'Hash counter');
sameGroup(['0001_2024-02-29.jpg','0002_2024-02-29.jpg','0003_2024-02-29.jpg'],'leap day');
assert.equal(key('0001_2026-02-30.png'),'','Impossible calendar day must not be treated as a trailing sequence');
assert.equal(key('0001_2025-02-29.png'),'','Leap-day validation');
assert.equal(key('0001_2026-13-05.png'),'','Impossible month');
assert.equal(key('0001_2026-06-00.png'),'','Zero day');
assert.equal(key('0000_2026-06-05.png'),'','Counter zero');
assert.equal(key('2024_2026-06-05.png'),'','A 4-digit year is not a leading counter');
assert.equal(key('2026-06-05.png'),'','Bare date is not an Image Set');
assert.equal(key('My_Trip_2026-06-05.png'),'','Date alone at end should not be interpreted as an image counter');
assert.equal(key('Vacation_2024.jpg'),'','Bare year suffix remains guarded');
assert.equal(key('2024 - Vacation.jpg'),'','Bare year prefix remains guarded');
assert.notEqual(key('0001_2026-06-06.png'),main,'Different date must not merge');
assert.notEqual(key('0001_2025-06-05.png'),main,'Different year must not merge');
assert.notEqual(key('0001_2026-06-05.png','Other <other@example.com>'),main,'Different poster must not merge');
assert.notEqual(key('0001_2026-06-05.png','Alice <poster@example.com>','alt.other'),main,'Different group must not merge');
assert.notEqual(key('0001_2026-06-05.mp4','Alice <poster@example.com>','alt.test','video'),main,'Different kind must not merge');
assert.equal(sameGroup(['Vacation_001.jpg','Vacation_002.jpg','Vacation_003.jpg'],'legacy trailing counters'),key('Vacation_004.jpg'));
assert.equal(sameGroup(['01 - Vacation.jpg','02 - Vacation.jpg','03 - Vacation.jpg'],'legacy leading counters'),key('04 - Vacation.jpg'));
assert.equal(sameGroup(['Vacation [01/25].jpg','Vacation [02/25].jpg','Vacation [03/25].jpg'],'legacy index/total'),key('Vacation [04/25].jpg'));
assert.equal(key('001.jpg','Alice <poster@example.com>','alt.test','image','My Album [1/20] "001.jpg" yEnc'),key('002.jpg','Alice <poster@example.com>','alt.test','image','My Album [2/20] "002.jpg" yEnc'),'Header index/total fallback');
assert(source.includes('members.length>=3'),'Minimum three-member media set guard must remain');
assert(source.includes("els.groupRelatedBtn.textContent=active?'▦ Image Sets: ON':'▦ Image Sets: OFF'"),'Image Sets toggle must remain');
console.log('validate-v3720-date-sequences.js: PASS (exact date-stamped filenames, dates/sequences, false-positive protections, original classifier compatibility)');
